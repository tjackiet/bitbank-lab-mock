import { fileURLToPath } from "node:url";
import { defineConfig } from "vitest/config";

/**
 * カバレッジの計測範囲と、退行を止める下限。
 *
 * テストの走らせ方そのものは既定のままで、この設定が持つのは**何を分母にするか**と
 * **どこまで下がったら落とすか**だけである。
 *
 * `npm test`（`vitest run`）は今までどおり計測しない。速い内側の輪を壊さないためで、
 * 計測は `npm run coverage` と CI（`.github/workflows/ci.yml`）が担う。
 */
export default defineConfig({
  test: {
    /**
     * テストの間だけ `undici` を番人へ差し替える（`tests/network-guard.ts`）。
     *
     * `src/engine/candles.ts` が持つ外向きの口はここ 1 つで、`SessionStore` は
     * スタブを渡し忘れるとそこへ落ちる。差し替えておけば、忘れた経路が**外へ出る前に**
     * 捕まる。`tests/no-network.ts` がそれをテストの失敗に変える。
     *
     * `resolve.alias` ではなく `test.alias` に置くのは、効き目をテストの実行中に限るため。
     */
    alias: {
      undici: fileURLToPath(new URL("./tests/network-guard.ts", import.meta.url)),
    },

    setupFiles: ["tests/no-network.ts"],

    /**
     * 番人をすり抜けたときの**宛先側の歯止め**。到達しないループバックへ向けておく。
     *
     * 番人（上の `alias`）は口を塞ぐが、塞ぐ仕掛けそのものが外れると素の `undici` に
     * 戻り、`defaultFetchCandles()` の既定は公開 API になる。実際に `alias` を外して
     * 試したとき、テストから公開 API へ向かう要求がそのまま走った。**大声で落ちる仕掛けと、
     * 黙って届かない宛先の 2 枚**にしておけば、片方が外れても外には出ない。
     *
     * 明示的に `baseUrl` を渡すテスト（`tests/engine/candles.test.ts`）はこれに影響されない
     * （`opts.baseUrl ?? process.env.BITBANK_PUBLIC_BASE_URL ?? DEFAULT_BASE_URL` の順）。
     * 既定が外向きであること自体は `tests/network-guard.test.ts` がこの値を外して確かめる。
     *
     * **認証のキーとシークレットは空にしておく。** モックを起こすのと同じ端末でこの 2 つを
     * export したまま `npm test` を流すと、`buildServer()` が環境変数から読んで検証を有効にし、
     * 認証ヘッダを付けない既存のテストが一斉に `20003` で落ちる。空文字は未設定として扱う
     * （`src/server/config.ts` の `apiCredentials()`）。子プロセスにも同じ値が渡るので、検証を
     * 有効にしたいテストは明示して上書きする（`tests/index.test.ts`）。
     */
    env: {
      BITBANK_PUBLIC_BASE_URL: "http://127.0.0.1:9",
      BITBANK_MOCK_API_KEY: "",
      BITBANK_MOCK_API_SECRET: "",
    },

    coverage: {
      provider: "v8",

      // 分母は製品コードだけ。tests/ 自身やこの設定ファイルを混ぜると数字が薄まる。
      include: ["src/**/*.ts"],

      /**
       * `src/index.ts` を外す。**テストが無いからではなく、この計測方法では測れないから**である。
       *
       * `tests/index.test.ts` は `src/index.ts` を子プロセスとして `spawn` して検証する
       * （状態ファイルの排他と起動引数）。v8 のカバレッジは子プロセスを追わないので、
       * 実際には通っている経路が 0% と出る。入れたままにすると下の閾値がこの 0% に
       * 引きずられ、**実測 92% の状態で下限を 87% に置く**ことになって意味を失う。
       *
       * 外す代わりに、`src/index.ts` の配線が外れたら `tests/index.test.ts` が落ちる。
       * 同ファイルの冒頭がその狙いを書いている。
       */
      exclude: ["src/index.ts"],

      reporter: ["text"],

      /**
       * 下限は計測値の少し下に置く**ラチェット**で、目標値ではない。
       * 2026-09-20 の実測は Stmt 94.28 / Branch 88.73 / Func 97.96 / Line 96.31
       * （92.49 / 86.87 / 97.46 / 94.53 → 93.59 / 87.85 / 97.96 / 95.60 → 94.03 / 88.61 /
       * 97.96 / 96.01 と上げてきた）。
       *
       * **上げ直す理由は「上がったから」ではなく「効かなくなったから」である。**
       * 下限を据え置いたまま計測値が上がると、その差のぶんだけ退行を通す。実際
       * 93 / 95 のままでは、下の「関数 1 本 + 文 11 + 分岐 8」の投入が**通ってしまった**
       * （実測。以前は文・分岐・行の 3 本で落ちていた）。
       *
       * 上げるのは実際に上がってからにする。**下げるときは、なぜ下げるかを PR に書くこと。**
       * 黙って下げられるなら、この下限は無いのと同じである。
       *
       * **どれだけの退行で落ちるかを実測して決めた**（未テストのコードを足して確認）。
       * この 4 つの下限では、新しく入った未到達のものが
       * 文 11 / 行 9 に達した時点で落ちる。実測した 2 点は
       * **文 4・行 3・関数 1 の素朴な補助関数は通り、文 18・行 10・関数 1 は文と行の 2 本で落ちる**。
       *
       * 計測値が上がった回でも、この投入が落ちるなら下限は据え置く。上の規則どおり、
       * 上げ直す理由は上がったことではなく**効かなくなったこと**である。
       *
       * `branches` を 87 のままにしているのは、分岐は粒度が粗く「効かせる」と
       * 「余白を残す」が両立しないためである（88.5 まで上げると余白が分岐 1 つになる）。
       * 実のあるコードは文と行の側で捕まるので、そちらに効かせている。
       *
       * 狙いは**3 文程度の素朴な補助関数は通し、実のあるコードが未テストで入ったら
       * 文と行の側で落ちる**という釣り合いである。関数の下限だけを極端に締めると
       * （実測では `functions` を 97.46 の状態で 97 にすると未テストの関数 1 本で落ちた）
       * 「赤くなったから下げる」を誘発し、下げられた時点でこの仕組み全体が死ぬ。
       *
       * **ファイル単位の下限（`perFile`）は置いていない。** 今の最低は
       * `src/engine/precision.ts` の Branch 75%（非有限値のガード 1 文。外しても挙動が
       * 変わらないので、カバレッジのためだけのテストは足していない）と
       * `src/routes/cancel-order.ts` / `src/routes/create-order.ts` の 77.27%
       * （Fastify が先に弾く本文の防御）で、いずれも「テストで上げる」筋のものではない。
       * 先に `perFile` を入れると、それらのために全体が赤いままになる。
       */
      thresholds: {
        statements: 93.5,
        branches: 87,
        functions: 97,
        lines: 95.5,
      },
    },
  },
});
